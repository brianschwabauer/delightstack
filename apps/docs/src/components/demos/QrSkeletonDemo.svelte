<script>
	import { QR } from '@delightstack/components/display';
	import { Button } from '@delightstack/components/actions';

	let loading = $state(true);
</script>

<div class="skeleton-demo">
	<Button dense onclick={() => (loading = !loading)}>
		{loading ? 'Show loaded' : 'Show skeleton'}
	</Button>
	<!-- The skeleton auto-dismisses the moment a `value` is available. -->
	<QR skeleton value={loading ? undefined : 'https://thedelight.co'} size={200} />
</div>

