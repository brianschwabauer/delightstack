/**
 * The SQL a declared schema produces, as text — for agents and people reading
 * a database they did not create, and for a committed snapshot that fails the
 * test suite when it drifts from the code.
 *
 * Pure: no Durable Object, no `cloudflare:workers`. The server builds its own
 * triggers with {@link changeTriggerStatements}, so the snapshot and the live
 * database cannot disagree about them.
 */

import type { Database } from '../schema/schema.js';
import {
	buildServerSearchTable,
	type SearchTableSource,
} from '../search/server/table_config.js';
import { planGeneratedColumns, quoteIdentifier } from '../search/server/sql_where.js';
import { whereContext } from '../search/server/engine.js';

/** The change-capture log (see db.server.ts, "Change capture"). */
export const CHANGES_TABLE = '_changes';

/** The write-marker column every entity table carries. */
export const WRITE_MARK_COLUMN = '_w';

/** Prefix of the change-capture triggers (`_chg_<table>_ins|upd|del`). */
export const CHANGE_TRIGGER_PREFIX = '_chg_';

/**
 * The three change-capture triggers for one table, as `[name, CREATE TRIGGER]`.
 *
 * Library writes flip `_w` in the same statement, so the insert and update
 * triggers only fire for writes that left it alone (raw SQL, a foreign key's
 * `SET NULL`). Library deletes write their search tombstone at the current
 * timestamp first, so the delete trigger only fires for raw deletes and
 * cascades. `before_columns` (the old row, as JSON) is captured only when the
 * catch-up needs it — history and file-GC tables.
 */
export function changeTriggerStatements(
	table_name: string,
	primary_key: string,
	before_columns: readonly string[],
): [name: string, ddl: string][] {
	const q = quoteIdentifier;
	const literal = `'${table_name}'`;
	const before = before_columns.length
		? `json_object(${before_columns.map((column) => `'${column}', OLD.${q(column)}`).join(', ')})`
		: 'NULL';
	// `stamped`: the raw write set `updated_at` itself (an insert with a real
	// timestamp, an update that changed it), so the catch-up keeps that value
	// instead of stamping a fresh one — backdating a row stays backdated.
	const log = (id: string, op: string, before_sql: string, stamped: string) =>
		`INSERT INTO ${q(CHANGES_TABLE)} (entity_type, entity_id, op, before, stamped) VALUES (${literal}, ${id}, '${op}', ${before_sql}, ${stamped});`;
	const name = (suffix: string) => `${CHANGE_TRIGGER_PREFIX}${table_name}_${suffix}`;
	const mark = q(WRITE_MARK_COLUMN);
	const pk = q(primary_key);
	return [
		[
			name('ins'),
			`CREATE TRIGGER ${q(name('ins'))} AFTER INSERT ON ${q(table_name)} WHEN NEW.${mark} = 0 BEGIN ${log(`NEW.${pk}`, 'insert', 'NULL', 'NEW."updated_at" > 0')} END;`,
		],
		[
			name('upd'),
			`CREATE TRIGGER ${q(name('upd'))} AFTER UPDATE ON ${q(table_name)} WHEN NEW.${mark} IS OLD.${mark} BEGIN ${log(`NEW.${pk}`, 'update', before, 'NEW."updated_at" IS NOT OLD."updated_at"')} INSERT INTO ${q(CHANGES_TABLE)} (entity_type, entity_id, op, before, stamped) SELECT ${literal}, OLD.${pk}, 'delete', ${before}, 0 WHERE NEW.${pk} IS NOT OLD.${pk}; END;`,
		],
		[
			name('del'),
			`CREATE TRIGGER ${q(name('del'))} AFTER DELETE ON ${q(table_name)} WHEN NOT EXISTS (SELECT 1 FROM search_tombstones WHERE entity_type = ${literal} AND doc_id = CAST(OLD.${pk} AS TEXT) AND deleted_at = (SELECT last_updated_at FROM search_state WHERE entity_type = ${literal})) BEGIN ${log(`OLD.${pk}`, 'delete', before, '0')} END;`,
		],
	];
}

/** Whether a table's raw-write catch-up needs the old row (history, file GC). */
export function capturesBeforeImage(table: Database.Table): boolean {
	return (
		table.config.history?.enabled === true ||
		Object.keys(table.config.file_fields ?? {}).length > 0
	);
}

/**
 * Every statement that creates the declared schema, as one readable SQL file:
 * tables (with the search engine's generated `sv$` columns inline), indexes
 * and change-capture triggers, each table preceded by a comment.
 *
 * Commit its output and assert it in a test, so the file always shows what
 * the database really is:
 *
 * @example
 * import { schemaSql } from '@delightstack/database/server';
 * it('schema.sql is current', async () => {
 * 	await expect(schemaSql(tables)).toMatchFileSnapshot('../schema.sql');
 * });
 */
export function schemaSql(tables: Record<string, Database.Table>): string {
	const out: string[] = [
		'-- Generated by schemaSql() from the declared schema. Do not edit by hand.',
		'--',
		'-- Raw SQL against these tables is fully supported: inserts, updates and',
		'-- deletes are captured by the _chg_* triggers and caught up (search index,',
		'-- sync timestamps, history, websocket broadcast) by DatabaseServer.',
		'-- Leave `_w` alone: library writes flip it so the triggers can tell them',
		'-- apart. Objects and arrays are JSON text in their own column.',
		'-- `json` holds FK-derived search values (and keys from older schemas).',
		'',
	];
	for (const [entity_type, table] of Object.entries(tables)) {
		const definition = table.config.table_definition as
			| Record<string, string>
			| undefined;
		if (!definition) continue;
		const table_name = table.name.toLowerCase();
		const full: Record<string, string> = {
			...definition,
			json: 'TEXT',
			[WRITE_MARK_COLUMN]: 'INTEGER NOT NULL DEFAULT 0',
		};
		const search = buildServerSearchTable(
			entity_type,
			table as unknown as SearchTableSource,
		);
		const generated = planGeneratedColumns(whereContext(search));
		const fields = (table as { _?: Record<string, { _?: Record<string, unknown> }> })._ ?? {};
		const note = (column: string, def: string): string => {
			const field = fields[column]?._;
			if (field?.type === 'enum' && Array.isArray(field.options)) {
				return `one of ${(field.options as string[]).map((o) => `'${o}'`).join(', ')}`;
			}
			if (/^BOOLEAN\b/.test(def)) return '0 or 1';
			if (column === 'created_at' || column === 'updated_at') return 'epoch ms';
			return '';
		};
		const lines: [sql: string, comment: string][] = [
			...Object.entries(full).map(
				([column, def]): [string, string] => [`\t${q(column)} ${def}`, note(column, def)],
			),
			...generated.map((spec): [string, string] => [
				`\t${q(spec.column)} GENERATED ALWAYS AS (${spec.expression}) VIRTUAL`,
				`search: ${spec.field}`,
			]),
		];
		// The comma goes before the comment, or the comment would swallow it
		const columns = lines.map(
			([sql, comment], i) =>
				`${sql}${i < lines.length - 1 ? ',' : ''}${comment ? ` -- ${comment}` : ''}`,
		);
		const notes = [
			table.config.history?.enabled
				? `history kept ${table.config.history.retention_days || 'forever'} days`
				: '',
			table.config.json_fields?.length
				? `JSON columns: ${table.config.json_fields.join(', ')}`
				: '',
		].filter(Boolean);
		out.push(`-- ${table_name}${notes.length ? ` (${notes.join('; ')})` : ''}`);
		out.push(`CREATE TABLE ${q(table_name)} (\n${columns.join('\n')}\n);`);
		const indexes = [
			...(table.config.indexes ?? []).map((index) => {
				const cols = index.columns
					.map((c) => `${q(c.column)} ${c.direction === 'DESC' ? 'DESC' : 'ASC'}`)
					.join(', ');
				return `CREATE${index.unique ? ' UNIQUE' : ''} INDEX ${q(index.name)} ON ${q(table_name)} (${cols})${index.where ? ` WHERE ${index.where}` : ''};`;
			}),
			`CREATE INDEX ${q(`idx_${table_name}_updated_at`)} ON ${q(table_name)} ("updated_at", ${q(search.primary_key)});`,
			...generated.map(
				(spec) =>
					`CREATE INDEX ${q(spec.index_name)} ON ${q(table_name)} (${q(spec.column)});`,
			),
		];
		out.push(...indexes);
		const blob = new Set(table.config.blob_fields ?? []);
		const before = capturesBeforeImage(table)
			? Object.keys(full).filter(
					(column) => column !== WRITE_MARK_COLUMN && !blob.has(column),
				)
			: [];
		for (const [, ddl] of changeTriggerStatements(
			table_name,
			search.primary_key,
			before,
		)) {
			out.push(ddl);
		}
		out.push('');
	}
	return out.join('\n');
}

function q(name: string): string {
	return quoteIdentifier(name);
}
